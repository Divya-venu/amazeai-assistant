import React, { useState } from 'react';
import { Sparkles, TrendingUp, AlertTriangle, Lightbulb, Loader, Play } from 'lucide-react';
import aiService from '../services/aiService';

const AIControls = ({ onUpdate, dataset }) => {
    const [loading, setLoading] = useState({
        forecast: false,
        anomalies: false,
        insights: false,
        recommendations: false
    });
    const [error, setError] = useState('');

    const shopId = "saas-demo-shop";

    const handleAction = async (actionType) => {
        if (!dataset || dataset.length === 0) {
            setError('Please provide a dataset first.');
            return;
        }

        setLoading(prev => ({ ...prev, [actionType]: true }));
        setError('');

        try {
            if (actionType === 'forecast') {
                const res = await aiService.generateForecast(shopId, dataset);
                onUpdate({ forecast: res.data.forecast });
            } else if (actionType === 'anomalies') {
                const res = await aiService.runAnomalyDetection(shopId, dataset);
                onUpdate({ anomalies: res.data.anomalies });
            } else if (actionType === 'insights' || actionType === 'recommendations') {
                // Insights and recommendations are generated by the same LLM endpoint
                const res = await aiService.generateInsights(shopId, dataset);
                onUpdate({ insights: res.data });
            }
        } catch (err) {
            console.error(`[AIControls] Error running ${actionType}:`, err);
            setError(err.response?.data?.error || `Failed to run ${actionType}.`);
        } finally {
            setLoading(prev => ({ ...prev, [actionType]: false }));
        }
    };

    const actions = [
        { id: 'forecast', label: 'Revenue Forecast', icon: TrendingUp, color: 'text-indigo-400', bg: 'bg-indigo-500/10' },
        { id: 'anomalies', label: 'Detect Anomalies', icon: AlertTriangle, color: 'text-red-400', bg: 'bg-red-500/10' },
        { id: 'insights', label: 'Generate AI Insights', icon: Sparkles, color: 'text-sky-400', bg: 'bg-sky-500/10' },
        { id: 'recommendations', label: 'Business Recommendations', icon: Lightbulb, color: 'text-amber-400', bg: 'bg-amber-500/10' }
    ];

    return (
        <div className="w-full bg-slate-800/50 rounded-xl border border-slate-700 shadow-xl p-5 mb-4 flex flex-col">
            <h2 className="text-lg font-bold text-white mb-2 flex items-center gap-2">
                <Play className="text-emerald-400" size={20} />
                AI Actions
            </h2>
            <p className="text-slate-400 text-[13px] mb-5 leading-relaxed">
                Run specific AI models on your currently active dataset.
            </p>

            <div className="grid grid-cols-1 gap-3">
                {actions.map((action) => {
                    const Icon = action.icon;
                    const isLoading = loading[action.id];
                    return (
                        <button
                            key={action.id}
                            onClick={() => handleAction(action.id)}
                            disabled={isLoading}
                            className={`flex items-center justify-between px-4 py-3 rounded-lg border border-slate-700/50 hover:border-slate-500 transition-colors bg-slate-900/50 group ${isLoading ? 'opacity-70 cursor-not-allowed' : ''}`}
                        >
                            <div className="flex items-center gap-3">
                                <div className={`p-2 rounded-md ${action.bg}`}>
                                    <Icon size={16} className={action.color} />
                                </div>
                                <span className="text-sm font-medium text-slate-200 group-hover:text-white transition-colors">{action.label}</span>
                            </div>
                            {isLoading ? (
                                <Loader size={16} className="animate-spin text-slate-400" />
                            ) : (
                                <div className="w-6 h-6 rounded-full bg-slate-800 flex items-center justify-center opacity-0 group-hover:opacity-100 transition-opacity">
                                    <Play size={10} className="text-slate-400 translate-x-[1px]" />
                                </div>
                            )}
                        </button>
                    )
                })}
            </div>

            {error && (
                <div className="mt-4 p-3 bg-red-500/10 border border-red-500/20 rounded-lg text-red-400 text-xs flex items-center gap-2 relative">
                   <AlertTriangle size={14} className="shrink-0" />
                   {error}
                </div>
            )}
        </div>
    );
};

export default AIControls;
