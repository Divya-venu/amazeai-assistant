const PDFDocument = require('pdfkit');
const asyncHandler = require('../utils/asyncHandler');
const Sale = require('../models/Sale');
const Expense = require('../models/Expense');

/**
 * @desc    Generate AI Business PDF Report
 * @route   GET /api/reports/generate
 * @access  Private/Admin
 */
exports.generateBusinessReport = asyncHandler(async (req, res) => {
    const shopId = req.shopId;

    // 1. Fetch Data for Report using Aggregation for speed
    const [salesStats, expenseStats] = await Promise.all([
        Sale.aggregate([
            { $match: shopId ? { shopId } : {} },
            { 
                $group: { 
                    _id: null, 
                    totalRevenue: { $sum: { $multiply: ["$price", "$quantity"] } }
                } 
            }
        ]),
        Expense.aggregate([
            { $match: shopId ? { shopId } : {} },
            { 
                $group: { 
                    _id: null, 
                    totalExpenses: { $sum: "$amount" } 
                } 
            }
        ])
    ]);

    const totalRevenue = salesStats[0]?.totalRevenue || 0;
    const totalExpenses = expenseStats[0]?.totalExpenses || 0;
    const netProfit = totalRevenue - totalExpenses;
    const profitMargin = totalRevenue > 0 ? ((netProfit / totalRevenue) * 100).toFixed(2) : 0;

    // 3. Create PDF
    const doc = new PDFDocument({ margin: 50 });

    const filename = `AI_Business_Report_${new Date().toISOString().split('T')[0]}.pdf`;
    
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `attachment; filename=${filename}`);

    doc.pipe(res);

    // --- PDF Content ---
    
    // Header
    doc.fillColor('#4f46e5').fontSize(26).text('AI BUSINESS INTELLIGENCE', { align: 'center' });
    doc.fillColor('#374151').fontSize(12).text('Strategic Performance Report', { align: 'center' });
    doc.moveDown();
    doc.strokeColor('#e5e7eb').moveTo(50, doc.y).lineTo(550, doc.y).stroke();
    doc.moveDown(2);

    // Summary Section
    doc.fillColor('#111827').fontSize(18).text('Business Executive Summary', { underline: true });
    doc.moveDown();
    
    doc.fontSize(12).fillColor('#4b5563');
    doc.text(`Report Date: ${new Date().toLocaleDateString()}`);
    doc.text(`Total Revenue: $${totalRevenue.toLocaleString()}`);
    doc.text(`Total Expenses: $${totalExpenses.toLocaleString()}`);
    doc.fillColor(netProfit >= 0 ? '#059669' : '#dc2626');
    doc.text(`Net Profit: $${netProfit.toLocaleString()}`);
    doc.fillColor('#4b5563');
    doc.text(`Profit Margin: ${profitMargin}%`);
    
    doc.moveDown(2);

    // AI Insights Section
    doc.fillColor('#111827').fontSize(18).text('AI Insights & Recommendations', { underline: true });
    doc.moveDown();
    
    doc.fontSize(12).fillColor('#4b5563');
    doc.text('Based on our latest AI analysis, here are your strategic priorities:');
    doc.moveDown();
    
    const recommendations = [
        "Focus on increasing marketing spend for the electronics category.",
        "Reduce inventory for low-performing product lines to optimize cash flow.",
        "Shift advertising focus to high-ROI digital channels based on recent trends.",
        "Consider seasonal pricing adjustments for top-selling items.",
        "Streamline operational expenses in the logistics department."
    ];

    recommendations.forEach((rec, index) => {
        doc.text(`${index + 1}. ${rec}`);
        doc.moveDown(0.5);
    });

    doc.moveDown(2);

// Footer
    doc.fontSize(10).fillColor('#9ca3af').text('Generated by AI Business Intelligence Platform - Confidential', { align: 'center' });

    doc.end();
});

const Report = require('../models/Report');
const { Parser } = require('json2csv');

exports.getReports = asyncHandler(async (req, res) => {
    const reports = await Report.find().sort({ date: -1 });
    res.status(200).json(reports);
});

exports.getReportById = asyncHandler(async (req, res) => {
    const report = await Report.findById(req.params.id);
    if (!report) {
        return res.status(404).json({ error: 'Report not found' });
    }
    res.status(200).json(report);
});

exports.downloadReportCSV = asyncHandler(async (req, res) => {
    const report = await Report.findById(req.params.id);
    if (!report) {
        return res.status(404).json({ error: 'Report not found' });
    }

    // Convert summaryData to CSV
    const fields = ['Metric', 'Value'];
    const data = [
        { Metric: 'Total Revenue', Value: report.summaryData.totalRevenue },
        { Metric: 'Total Orders', Value: report.summaryData.totalOrders },
        { Metric: 'Unique Customers', Value: report.summaryData.uniqueCustomers },
        { Metric: 'Average Order Value', Value: report.summaryData.avgOrderValue },
    ];

    const json2csvParser = new Parser({ fields });
    const csvData = json2csvParser.parse(data);

    res.setHeader('Content-Type', 'text/csv');
    res.setHeader('Content-Disposition', `attachment; filename=${report.name.replace(/\s+/g, '_')}_${report.date.toISOString().split('T')[0]}.csv`);
    
    res.status(200).send(csvData);
});
